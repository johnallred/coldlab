"""The health record: one line per run, and a table generated from the lines.

The interesting figure is not pass or fail. It is the flake rate. A lab that
fails one run in twenty is a worse problem than one that fails every time,
because the second gets fixed and the first gets blamed on the student.
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path


def append_record(path: str | Path, record: dict) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(record, sort_keys=True) + "\n")


def load_records(path: str | Path) -> list[dict]:
    path = Path(path)
    if not path.exists():
        return []
    records = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line:
            records.append(json.loads(line))
    return records


def summarize(records: list[dict]) -> dict:
    if not records:
        return {"runs": 0, "passed": 0, "pass_rate": None,
                "median_seconds": None, "checks": {}}

    durations = [r["seconds"] for r in records if r.get("seconds") is not None]
    passed = sum(1 for r in records if r.get("passed"))

    per_check: dict[str, dict] = {}
    for record in records:
        for check in record.get("checks", []):
            entry = per_check.setdefault(
                check["name"],
                {"runs": 0, "failures": 0, "gating": check.get("gating", True)},
            )
            entry["runs"] += 1
            if not check["ok"]:
                entry["failures"] += 1

    for entry in per_check.values():
        entry["failure_rate"] = entry["failures"] / entry["runs"]
        # A check that always passes is stable. One that always fails is
        # broken and will get fixed. One that does both is the dangerous kind.
        entry["flaky"] = 0 < entry["failures"] < entry["runs"]

    return {
        "runs": len(records),
        "passed": passed,
        "pass_rate": passed / len(records),
        "median_seconds": statistics.median(durations) if durations else None,
        "checks": per_check,
    }


def render(summary: dict, records: list[dict]) -> str:
    if not summary["runs"]:
        return ("# Lab health\n\nNo runs recorded yet. "
                "`python -m harness.run` writes the first one.\n")

    first = min(r["started_at"] for r in records)
    last = max(r["started_at"] for r in records)
    flaky = sorted(n for n, c in summary["checks"].items() if c["flaky"])

    lines = [
        "# Lab health",
        "",
        "GENERATED by `python -m harness.report`. Do not edit.",
        "",
        f"- Runs: **{summary['runs']}**, first {first}, last {last}",
        f"- Pass rate: **{summary['pass_rate'] * 100:.0f}%** "
        f"({summary['passed']} of {summary['runs']})",
        f"- Median duration: **{summary['median_seconds']:.0f}s**"
        if summary["median_seconds"] is not None else "- Median duration: n/a",
        "",
    ]

    if flaky:
        lines += [
            "## Flaky checks",
            "",
            "These both passed and failed across recorded runs, which is worse",
            "than a check that always fails. Each one is a real defect in the",
            "lab, the harness, or an assumption about eventual consistency.",
            "",
        ]
        lines += [f"- `{name}` "
                  f"({summary['checks'][name]['failures']} of "
                  f"{summary['checks'][name]['runs']} runs failed)"
                  for name in flaky]
        lines.append("")
    else:
        lines += ["No check has both passed and failed yet.", ""]

    lines += [
        "## Every check",
        "",
        "| Check | Gating | Runs | Failures | Failure rate |",
        "|---|---|---|---|---|",
    ]
    for name in sorted(summary["checks"]):
        c = summary["checks"][name]
        lines.append(
            f"| `{name}` | {'yes' if c['gating'] else 'advisory'} | "
            f"{c['runs']} | {c['failures']} | {c['failure_rate'] * 100:.0f}% |"
        )
    lines.append("")
    return "\n".join(lines)


# The README quotes the health figures rather than restating them, so a
# number there cannot drift from the record it describes. Everything between
# these markers is generated; everything outside is written by hand.
README_START = "<!-- health:start -->"
README_END = "<!-- health:end -->"


def readme_block(summary: dict) -> str:
    if not summary["runs"]:
        return ("No runs recorded yet. `python -m harness.run` writes the "
                "first one.")

    lines = [
        f"- Runs: **{summary['runs']}**",
        f"- Pass rate: **{summary['pass_rate'] * 100:.0f}%** "
        f"({summary['passed']} of {summary['runs']})",
    ]
    if summary["median_seconds"] is not None:
        lines.append(f"- Median duration: **{summary['median_seconds']:.0f}s**")

    flaky = sorted(n for n, c in summary["checks"].items() if c["flaky"])
    if flaky:
        listed = ", ".join(f"`{name}`" for name in flaky)
        lines.append(f"- Checks that have both passed and failed: {listed}")
    else:
        lines.append("- No check has both passed and failed")

    lines.append("")
    lines.append("Generated from [`health/health.jsonl`](health/health.jsonl) "
                 "by `python -m harness.report`. Full table in "
                 "[`health/HEALTH.md`](health/HEALTH.md).")
    return "\n".join(lines)


def update_readme(path: str | Path, summary: dict) -> bool:
    """Replace the marked block. True when the file changed."""
    path = Path(path)
    text = path.read_text(encoding="utf-8")

    if README_START not in text or README_END not in text:
        raise ValueError(
            f"{path} has no {README_START} / {README_END} markers, so the "
            "health figures cannot be generated into it. Add them, rather "
            "than typing figures in by hand."
        )

    before, _, rest = text.partition(README_START)
    _, _, after = rest.partition(README_END)
    updated = (f"{before}{README_START}\n{readme_block(summary)}\n"
               f"{README_END}{after}")

    if updated == text:
        return False
    path.write_text(updated, encoding="utf-8")
    return True


def regenerate(jsonl: str | Path, markdown: str | Path,
               readme: str | Path | None = None) -> dict:
    records = load_records(jsonl)
    summary = summarize(records)
    Path(markdown).write_text(render(summary, records), encoding="utf-8")
    if readme is not None:
        update_readme(readme, summary)
    return summary


if __name__ == "__main__":
    s = regenerate("health/health.jsonl", "health/HEALTH.md", "README.md")
    print(f"health/HEALTH.md and README.md regenerated from {s['runs']} runs")
